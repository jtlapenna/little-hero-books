import { createHash, randomBytes } from 'node:crypto';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanRepository } from './check-repository-secrets.ts';

const repo = mkdtempSync(path.join(tmpdir(), 'lhl-secret-test-'));
const sourceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const binary = process.env.GITLEAKS_BIN || 'gitleaks';
try {
  execFileSync('git', ['init', '-q', repo]);
  writeFileSync(path.join(repo, '.gitleaks.toml'), readFileSync(path.join(sourceRoot, '.gitleaks.toml')));
  mkdirSync(path.join(repo, 'scripts/security'), { recursive: true });
  const fingerprintPath = path.join(repo, 'scripts/security/compromised-credential-fingerprints.json');
  writeFileSync(fingerprintPath, '[]');
  writeFileSync(path.join(repo, 'safe.md'), 'Use runtime credential storage.');
  assert.equal(scanRepository(repo, binary).findings.length, 0);
  const header = Buffer.from(JSON.stringify({ alg: 'HS256', typ: 'JWT' })).toString('base64url');
  const claims = Buffer.from(JSON.stringify({ role: 'service_role', ref: 'synthetic-project' })).toString('base64url');
  const secret = [header, claims, Buffer.from('synthetic-invalid-signature').toString('base64url')].join('.');
  writeFileSync(path.join(repo, 'leak.md'), `Credential: ${secret}\n`);
  const findings = scanRepository(repo, binary).findings;
  assert(findings.some(row => row.file === 'leak.md' && row.rule === 'jwt'));
  assert(!JSON.stringify(findings).includes(secret));
  const child = spawnSync(process.execPath, [...process.execArgv, path.join(sourceRoot, 'scripts/security/check-repository-secrets.ts'),
    '--repo', repo, '--gitleaks', binary], { encoding: 'utf8' });
  assert.equal(child.status, 1);
  assert(!`${child.stdout}${child.stderr}`.includes(secret), 'CLI must never print the credential');
  rmSync(path.join(repo, 'leak.md'));
  const unlabelled = randomBytes(32).toString('hex');
  writeFileSync(fingerprintPath, JSON.stringify([createHash('sha256').update(unlabelled).digest('hex')]));
  writeFileSync(path.join(repo, 'copied-notes.md'), `Variable Name: BACKEND_API_TOKEN\nValue: ${unlabelled}\n`);
  assert(scanRepository(repo, binary).findings.some(row => row.file === 'copied-notes.md' && row.rule === 'known-compromised-credential'));
  rmSync(path.join(repo, 'copied-notes.md'));
  writeFileSync(path.join(repo, 'bare-token.ts'), `const header = 'Bearer ${unlabelled}';`);
  assert(scanRepository(repo, binary).findings.some(row => row.file === 'bare-token.ts' && row.rule === 'known-compromised-credential'));
  rmSync(path.join(repo, 'bare-token.ts'));
  writeFileSync(path.join(repo, 'sentence.md'), `Use ${unlabelled}.`);
  assert(scanRepository(repo, binary).findings.some(row => row.file === 'sentence.md' && row.rule === 'known-compromised-credential'));
  rmSync(path.join(repo, 'sentence.md'));
  writeFileSync(fingerprintPath, '[]');
  const modernKey = ['sb', 'secret', randomBytes(24).toString('base64url')].join('_');
  writeFileSync(path.join(repo, 'unlabelled.md'), `Use ${modernKey}.`);
  assert(scanRepository(repo, binary).findings.some(row => row.file === 'unlabelled.md' && row.rule === 'supabase-server-secret'));
  rmSync(path.join(repo, 'unlabelled.md'));
  const publicName = ['NEXT_PUBLIC_SUPABASE', 'SERVICE_ROLE_KEY'].join('_');
  writeFileSync(path.join(repo, 'unsafe.ts'), `const value = process.env.${publicName};`);
  assert(scanRepository(repo, binary).findings.some(row => row.rule === 'public-privileged-supabase-key'));
  rmSync(path.join(repo, 'unsafe.ts'));
  writeFileSync(path.join(repo, '.env.production'), 'IGNORED_VALUE=synthetic');
  assert(scanRepository(repo, binary).findings.some(row => row.rule === 'tracked-private-env-file'));
  rmSync(path.join(repo, '.env.production'));
  const backup = path.join(repo, 'docs/n8n-workflow-files/repo-centric/live-backups/test.json');
  mkdirSync(path.dirname(backup), { recursive: true }); writeFileSync(backup, '{}');
  assert(scanRepository(repo, binary).findings.some(row => row.rule === 'tracked-live-workflow-backup'));
  assert.throws(() => scanRepository(repo, path.join(repo, 'missing-scanner')), /did not complete/);
  console.log('Repository scan integration and redaction tests passed');
} finally { rmSync(repo, { recursive: true, force: true }); }
